""" Q1. Difference between / and //?
Answer:
/ → True division (returns float)
// → Floor division (returns integer or float)"""

# Example

a=5 / 2     # 2.5
b=5 // 2    # 2
c= -5 // 2   # -3  (important!)
print(a,b,c,sep="\n")

m=2
n=3
print("Value of m*n is:",m*n)
print("Value of m**n is:",m**n)

